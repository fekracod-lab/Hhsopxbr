List<String> getRegionsForGovernorate(String govName) {
  final cleanGov = govName.trim().replaceAll('محافظة', '').trim();
  if (kIraqiRegions.containsKey(cleanGov)) {
    return List<String>.from(kIraqiRegions[cleanGov]!);
  }
  for (final entry in kIraqiRegions.entries) {
    if (cleanGov.contains(entry.key) || entry.key.contains(cleanGov)) {
      return List<String>.from(entry.value);
    }
  }
  return ['مركز المحافظة', 'قضاء 1', 'قضاء 2'];
}

List<String> getSubRegionsForRegion(String regName) {
  final cleanName = regName.trim().replaceAll('قضاء', '').replaceAll('ناحية', '').trim();
  if (kIraqiSubRegions.containsKey(regName)) {
    return List<String>.from(kIraqiSubRegions[regName]!);
  }
  if (kIraqiSubRegions.containsKey(cleanName)) {
    return List<String>.from(kIraqiSubRegions[cleanName]!);
  }
  for (final entry in kIraqiSubRegions.entries) {
    if (cleanName.contains(entry.key) || entry.key.contains(cleanName)) {
      return List<String>.from(entry.value);
    }
  }
  return [
    'مركز $regName',
    'حي المعلمين',
    'حي الشهداء',
    'حي الفرات',
    'حي الرسالة',
    'حي التأميم',
  ];
}
