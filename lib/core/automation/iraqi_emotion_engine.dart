  /// تحليل النص واستخراج الشعور المقترن به
  static EmotionAnalysisResult? analyzeEmotion(String text) {
    final clean = text.toLowerCase().trim();
    final random = Random();

    for (final entry in _emotionKeywords.entries) {
      for (final kw in entry.value) {
        if (clean.contains(kw.toLowerCase())) {
          final responses = _emotionResponses[entry.key] ?? [];
          final selectedResponse = responses.isNotEmpty
              ? responses[random.nextInt(responses.length)]
              : 'يا هلا بيك عيوني، تدلل!';

          String? actionType;
          String? actionData;

          if (entry.key == IraqiEmotion.hunger) {
            actionType = 'navigate';
            actionData = '/restaurants';
          } else if (entry.key == IraqiEmotion.fatigue) {
            actionType = 'navigate';
            actionData = '/taxi';
          } else if (entry.key == IraqiEmotion.anger) {
            actionType = 'launch_whatsapp';
            actionData = 'support';
          }

          return EmotionAnalysisResult(
            emotion: entry.key,
            confidence: 0.95,
            matchedKeyword: kw,
            suggestedResponse: selectedResponse,
            suggestedActionType: actionType,
            suggestedActionData: actionData,
          );
        }
      }
    }
    return null;
  }
