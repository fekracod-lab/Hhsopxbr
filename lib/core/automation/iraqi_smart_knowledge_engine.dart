import 'package:dalal_alqaim/core/automation/smart_assistant_memory.dart';

/// محرك المعرفة العراقي الذكي لسكوزمي (Iraqi Smart Knowledge Engine)
/// يقدم إجابات ذكية وتفصيلية وودودة للغاية باللهجة العراقية بدون الاكتفاء بردود جافة أو تكرار
class IraqiSmartKnowledgeEngine {
  static String getSmartAnswer(String query, {String currentRoute = '/home', String? userName}) {
    final memory = SmartAssistantMemory();
    final name = memory.customNickname ?? userName ?? 'يا غالي';
    final q = query.toLowerCase().trim();
    final normalized = _normalizeArabic(q);

    // ────────────────────────────────────────────────────────
    // 1. استفسارات الوظائف والعمل والسيرة الذاتية (Career & Jobs)
    // ────────────────────────────────────────────────────────
    if (_matchesAny(normalized, [
      'وظائف', 'وظيفة', 'شغل', 'فرص عمل', 'سيرة ذاتية', 'سي في', 'cv', 'راتب', 'رواتب',
      'اقدم على شغل', 'ادور شغل', 'محتاج موظف', 'انشر وظيفة', 'مقابلة عمل', 'نصائح عمل'
    ])) {
      if (_matchesAny(normalized, ['سيرة ذاتية', 'سي في', 'cv', 'اكتبلي نبذة', 'اكتبلي عني', 'سيرتي'])) {
        return 'SAY: "تدلل يا $name من عيوني! علمود ترتب سيرة ذاتية مميزة لأصحاب العمل بالقائم:\n\n'
            '1⃣ افتح صفحة الوظائف وادخل على تبويب ( بروفايلي المهني).\n'
            '2⃣ اضغط على زر ( توليد بسكوزمي) وراح أصيغلك نبذة احترافية بمهاراتك وسنوات خبرتك.\n'
            '3⃣ حدد تخصصك (كاشير، مهندس، سائق، مبيعات...) وخلي رقم واتسابك شغال.\n\n'
            'تريد أنقلك لصفحة الوظائف هسة؟ "';
      }
      if (_matchesAny(normalized, ['راتب', 'رواتب', 'شكد ينطون', 'شكد الراتب', 'اجور'])) {
        return 'SAY: "يا هلا بيك $name! رواتب الوظائف بالقائم تختلف حسب المجال والدوام:\n\n'
            'وظائف الكاشير والمبيعات بالمتاجر: تبدأ عادة من 300,000 إلى 500,000 دينار شهرياً.\n'
            'وظائف التوصيل والكباتن: دخل يومي مجزي يوصل لأكثر من 600,000 إلى 900,000 دينار حسب عدد الطلبات.\n'
            'الوظائف التقنية والتدريس والمهندسين: من 600,000 إلى أكثر من مليون دينار.\n\n'
            'تكدر تتصفح قسم الوظائف بمدار وتشوف الراتب المعروض لكل إعلان مباشرة! "';
      }
      if (_matchesAny(normalized, ['انشر وظيفة', 'اريد موظف', 'محتاج عمال', 'محتاج كاشير', 'صاحب عمل'])) {
        return 'JOB_ADD';
      }
      return 'SAY: "يا هلا ومية هلا بيك $name! بقسم الوظائف بمدار عدنا:\n\n'
          '1⃣ **فرص العمل المتاحة**: وظائف من أصحاب المحلات والشركات بالقائم والأنبار مع أزرار التقديم والتواصل واتساب.\n'
          '2⃣ **دليل الكفاءات والباحثين**: بروفايلات الشباب المتاحين للعمل فوراً.\n'
          '3⃣ **بروفايلك المهني**: تكدر تثبت مهاراتك وخبراتك ليتواصلون وياك أصحاب العمل.\n\n'
          'شنو تحب نسوي هسة؟ أدورلك على وظيفة معينة، لو أنقلك للقسم؟ "';
    }

    // ────────────────────────────────────────────────────────
    // 2. استفسارات المطاعم والأكلات والوجبات (Restaurants & Food)
    // ────────────────────────────────────────────────────────
    if (_matchesAny(normalized, [
      'مطعم', 'مطاعم', 'اكل', 'وجبة', 'بيتزا', 'برجر', 'شاورما', 'قص', 'كباب', 'مشاوي',
      'جوعان', 'عشاء', 'غداء', 'ريوق', 'ساندويش', 'حلويات', 'عصائر', 'منيو'
    ])) {
      if (_matchesAny(normalized, ['بيتزا', 'برجر', 'شاورما', 'قص', 'كباب', 'مشاوي'])) {
        return 'NAVIGATE: "/restaurants"';
      }
      if (_matchesAny(normalized, ['شنو احسن مطعم', 'رشحلي مطعم', 'شنو اطلب', 'شنو طيب', 'اكل طيب'])) {
        return 'SAY: "تدلل عيوني $name! بالقائم وبمدار عدنا خيارات تخبل وتوصلك حارة ومقرمشة:\n\n'
            ' **مشاوي وكباب عراقي أصيل**: مشاوي البركة والسلطان.\n'
            ' **بيتزا وفطاير إيطالية**: بيتزا الصاج والجبن السايح.\n'
            ' **برجر وساندويشات سريعة**: برجر دبل لحم وجبن مع مقبلات.\n'
            ' **شاورما وقص تركي**: صاج شاورما لحم أو دجاج.\n\n'
            'اضغط على قسم المطاعم بالأسفل وتصفح المنيو واطلب بلمسة وحدة وتدلل! "';
      }
      return 'SAY: "يا هلا بأغلى $name! قسم المطاعم بمدار يجمعلك كل مطاعم القائم في مكان واحد مع التوصيل السريع للمنزل أو المحل. تكدر تختار وجبتك وتضيفها للسلة فوراً!"';
    }

    // ────────────────────────────────────────────────────────
    // 3. استفسارات تكسي وتوصيل مدار (Taxi & Rides)
    // ────────────────────────────────────────────────────────
    if (_matchesAny(normalized, [
      'تكسي', 'تاكسي', 'سيارة', 'توصيل', 'كابتن', 'مشوار', 'طلب سيارة', 'حجز تكسي', 'اريد سيارة'
    ])) {
      if (_matchesAny(normalized, ['اسجل كابتن', 'اشتغل كابتن', 'اشتغل سائق', 'تسجيل سائق'])) {
        return 'LAUNCH_WHATSAPP: "taxi"';
      }
      return 'SAY: "تدلل من عيوني $name! خدمة تكسي مدار توصلك وين ما تريد بالقائم والأنبار بأمان وسرعة وأنسب الأسعار.\n\n'
          'حدد موقعك والوجهة.\n'
          'يوصلك أقرب كابتن مع تتبع مساره على الخريطة مباشرة.\n\n'
          'تريد أفتحلك واجهة طلب تكسي مدار هسة؟ "';
    }


    // ────────────────────────────────────────────────────────
    // 5. استفسارات العقارات والبيوت والإيجار (Real Estate)
    // ────────────────────────────────────────────────────────
    if (_matchesAny(normalized, [
      'عقار', 'عقارات', 'بيت', 'شقة', 'ارض', 'محل', 'ايجار', 'إيجار', 'للبيع', 'شراء بيت', 'دلالية'
    ])) {
      if (_matchesAny(normalized, ['انشر عقار', 'اضيف بيت', 'اعلن عن بيتي', 'بيع بيتي'])) {
        return 'REAL_ESTATE_ADD';
      }
      return 'SAY: "يا هلا بيك عيوني $name! سوق العقارات في مدار يسهل عليك:\n\n'
          'تصفح البيوت والشقق والأراضي المعروضة للبيع أو الإيجار في القائم ومحيطها بالصور والأسعار والمساحة.\n'
          'نشر إعلان عقارك أو محلك مجاناً ليوصل لآلاف الزبائن.\n\n'
          'هسة أنقلك لقسم العقارات وتدلل من عيوني! "';
    }

    // ────────────────────────────────────────────────────────
    // 6. استفسارات مرسال والطرود والتسوق (Delivery & Stores)
    // ────────────────────────────────────────────────────────
    if (_matchesAny(normalized, [
      'مرسال', 'طرد', 'غراض', 'توصيل غرض', 'متجر', 'متاجر', 'سوق', 'مسواك', 'تسوق', 'جملة'
    ])) {
      if (_matchesAny(normalized, ['مرسال', 'طرد', 'غراض', 'توصيل غرض'])) {
        return 'DELIVERY_START';
      }
      return 'NAVIGATE: "/stores"';
    }

    // ────────────────────────────────────────────────────────
    // 7. استفسارات النقاط والمحفظة والوضع الليلي (Settings & Points)
    // ────────────────────────────────────────────────────────
    if (_matchesAny(normalized, ['نقاطي', 'نقاط', 'محفظتي', 'رصيدي', 'جوائز', 'مكافآت'])) {
      return 'POINTS_AND_WALLET';
    }
    if (_matchesAny(normalized, ['وضع ليلي', 'دارك مود', 'الوضع الداكن', 'الوضع الليلي', 'ظلام'])) {
      return 'THEME_DARK';
    }
    if (_matchesAny(normalized, ['وضع نهاري', 'لايت مود', 'الوضع الفاتح', 'شمس', 'نهار'])) {
      return 'THEME_LIGHT';
    }

    // ────────────────────────────────────────────────────────
    // 8. استفسارات الشكاوى وبلاغات الخريطة (Complaints & Civic Map)
    // ────────────────────────────────────────────────────────
    if (_matchesAny(normalized, [
      'شكوى', 'شكاوى', 'بلاغ', 'حفرة', 'حفر', 'تخسف', 'ماء فايض', 'بوري مكسور', 'واير مقطوع', 'محولة', 'مجاري', 'منهول', 'زبالة', 'نفايات', 'انارة طافية'
    ])) {
      if (_matchesAny(normalized, ['ابلغ عن حفرة', 'ابلغ عن ماء', 'اسجل بلاغ', 'انشر شكوى', 'عندي شكوى', 'اكتب شكوى'])) {
        return 'COMPLAINTS_ADD';
      }
      return 'SAY: "يا هلا بيك عيوني $name! خدمة **عين مدار** تتيح لك توثيق أي مشكلة بالشارع (حفرة، تخسف، ماء فايض، وايرات كهرباء، انسداد مجاري، أو تراكم نفايات) على الخريطة التفاعلية بالصور والموقع الدقيق لإيصالها لبلدية وكوادر القائم الخدمية.\n\nتريدني أنقلك لخريطة البلاغات هسة؟"';
    }

    // ────────────────────────────────────────────────────────
    // 9. المطور والبرمجة وهوية سكوزمي (Developer & Identity)
    // ────────────────────────────────────────────────────────
    if (_matchesAny(normalized, ['منو صنعك', 'منو برمجك', 'منو المطور', 'عمر الراوي', 'منو انت', 'شنو سكوزمي'])) {
      return 'SAY: "يا هلا بيك عيوني $name! أنا **سكوزمي** المساعد الذكي الرسمي لمنصة مدار المتكاملة، تم تطويري وبرمجتي وتصميمي بكل حب وإتقان بواسطة المطور العراقي المبدع **عمر الراوي** لخدمة أهلنا الكرام بالقائم والعراق وتسهيل كل أمور حياتهم اليومية!"';
    }

    // ────────────────────────────────────────────────────────
    // 9. المشاعر والذكاء العاطفي والفرفشة (Emotions & Chit-chat)
    // ────────────────────────────────────────────────────────
    if (_matchesAny(normalized, ['شلونك', 'اخبارك', 'شكو ماكو', 'احوالك', 'شلون صحتك'])) {
      return 'SAY: "بألف خير ونعمة ما دامك بخير يا أغلى $name! شلون يومك وشلون صحتك؟ إذا محتاج أي شي بالقائم تكسي، أكل، شغل، أو مكان كلي وتدلل من عيوني الثنتين!"';
    }
    if (_matchesAny(normalized, ['تعبان', 'مريض', 'راسي يوجعني', 'مالي خلق', 'ضايج', 'مقهور', 'مهموم'])) {
      return 'SAY: "سودة علية وسلامتك ألف سلامة يا $name فدوة اروحلك! ارتاح واشرب شي دافي وكلشي يهون وماكو شي يستاهل ضوجتك. إذا تحب اطلبلك تكسي يوصلك للبيت، أو أرشحلك دكتور شاطر يطمنك، كلي وهسة أرتبها إلك!"';
    }
    if (_matchesAny(normalized, ['فرحان', 'نجحت', 'تزوجت', 'انقبلت', 'فزت', 'مبروك'])) {
      return 'SAY: "ألف ألف مبروووك يا $name! عسى دوم الفرحة والضحكة بوجهك ويوم التخرج والترقية والخير الدائم! لازم نحتفل اليوم ونطلب حلويات وكنافة طيبة من قسم المطاعم بمدار!"';
    }
    if (_matchesAny(normalized, ['شكرا', 'مشكور', 'رحم الله والديك', 'عاشت ايدك', 'تسلم', 'ممنون'])) {
      return 'SAY: "تدلل عيوني $name، والديك بالجنة وربي يسلمك ويحفظك! أنا بالخدمة دائماً شوكت ما تحتاجني اضغط عليّه وتامر أمر!"';
    }
    if (_matchesAny(normalized, ['نكتة', 'شقة', 'ضحكني', 'شاقة وياي'])) {
      return 'SAY: "تدلل يا ورد! هاك هاي النكتة العراقية: \nواحد سأل صاحبه: تكدر تعد للعشرة بالإنكليزي؟\nكاله: أي ون تو ثري فور فايف سيكس سفن ايت ناين تن..\nكاله: عفية! زين بالعكس؟\nكاله: نت نايت تيس سكي.."';
    }

    // ────────────────────────────────────────────────────────
    // 10. الرد العام الذكي والمساعد (General Fallback)
    // ────────────────────────────────────────────────────────
    return 'SAY: "يا هلا ومية هلا بيك يا $name! أنا سكوزمي رفيقك ومساعدك الذكي بمدار.. كلي شنو ببالك؟\n\n'
        ' **حجز تكسي مدار**\n'
        ' **أطيب المطاعم والوجبات**\n'
        ' **فرص العمل والسيرة الذاتية**\n'
        ' **دليل الأطباء والمدرسين**\n'
        ' **سوق العقارات والبيوت**\n'
        ' **المتاجر وخدمة مرسال**\n\n'
        'اكتبلي شنو محتاج وهسة أساعدك فوراً وتدلل من عيوني! "';
  }

  static bool _matchesAny(String text, List<String> keywords) {
    return keywords.any((k) => text.contains(_normalizeArabic(k)));
  }

  static String _normalizeArabic(String text) {
    return text.toLowerCase()
        .replaceAll('أ', 'ا')
        .replaceAll('إ', 'ا')
        .replaceAll('آ', 'ا')
        .replaceAll('ة', 'ه')
        .replaceAll('ى', 'ي')
        .replaceAll('ئ', 'ي')
        .replaceAll('ؤ', 'و')
        .replaceAll('ء', '')
        .replaceAll('گ', 'ك')
        .replaceAll('چ', 'ج')
        .trim();
  }
}
