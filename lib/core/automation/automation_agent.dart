- NAVIGATE: "/route" (للانتقال لصفحة أخرى - فقط إذا المستخدم ليس عليها حالياً!)
- FETCH_SECTIONS: "كلمة_بحث" (لجلب الأقسام والخدمات من فايربيس)
- LAUNCH_WHATSAPP: "restaurant"أو "taxi"أو "support" (للتسجيل أو التواصل عبر واتساب)
