  /// إرسال طلب للذكاء الاصطناعي مع وعي بالصفحة الحالية
  Future<String> getNextAction(String uiDescription, String goal, {String currentRoute = '/home'}) async {
    await _ensureInitialized();
    await loadUserInfo();

    final prompt = '''
${_buildSystemPrompt(currentRoute)}

═══ هدف واستفسار المستخدم ═══
$goal

═══ حالة الواجهة الحالية ═══
$uiDescription

تذكر: أنت حالياً في الصفحة "$currentRoute". لا تستخدم NAVIGATE: "$currentRoute" أبداً!
إذا كان السؤال عام، أو طلب نصيحة، أو استفسار، أجب بـ SAY مع رد عراقي كامل ومفصل وودود!

ما هو الأمر التالي؟ (أمر واحد فقط)
''';

    try {
      final proxyResponse = await SmartAssistantConfig.askProxy(prompt);
      if (proxyResponse != null && proxyResponse.trim().isNotEmpty) {
        return proxyResponse.trim();
      }
    } catch (e) {
      debugPrint('خطأ في استجابة الذكاء الاصطناعي، الانتقال للمحرك المعرفي الذكي: $e');
    }

    return IraqiSmartKnowledgeEngine.getSmartAnswer(goal, currentRoute: currentRoute, userName: _userName);
  }

