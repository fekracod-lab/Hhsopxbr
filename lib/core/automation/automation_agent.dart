import 'smart_assistant_config.dart';
import 'smart_assistant_memory.dart';
import 'iraqi_smart_knowledge_engine.dart';

/// عميل الذكاء الاصطناعي "سكوزمي" - مخصص لتطبيق مدار
/// يتعرف على المستخدم وعلى الصفحة الحالية ويقدم ردود ذكية مخصصة
class AutomationAgent {
  String? _userName;
  String? _userRole;
  String? _userEmail;
  bool _userLoaded = false;
  bool _initialized = false;

  /// تهيئة النموذج
  Future<void> _ensureInitialized() async {
    if (_initialized) return;
    await SmartAssistantConfig.loadApiKey();
    _initialized = true;
  }

  /// تحميل بيانات المستخدم الحالي من Firebase
  Future<void> loadUserInfo() async {
    if (_userLoaded) return;
    try {
      final user = FirebaseAuth.instance.currentUser;
      if (user != null) {
        _userEmail = user.email;
        _userName = user.displayName;

        final doc = await FirebaseFirestore.instance
            .collection('users')
            .doc(user.uid)
            .get();
        if (doc.exists) {
          final data = doc.data()!;
          _userName = data['name'] ??
              data['fullName'] ??
              user.displayName ??
              'مستخدم مدار';
          _userRole = data['role'] ?? 'user';
        }
      }
    } catch (e) {
      debugPrint('خطأ في تحميل بيانات المستخدم: $e');
      _userName ??= 'مستخدم مدار';
    }
    _userLoaded = true;
  }

